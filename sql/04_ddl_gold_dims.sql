CREATE TABLE IF NOT EXISTS gold.d_calendario (
    sk_data                 integer     PRIMARY KEY, -- YYYYMMDD
    data                    date        NOT NULL UNIQUE,
    ano                     smallint    NOT NULL,
    semestre                smallint    NOT NULL,
    trimestre               smallint    NOT NULL,
    quadrimestre            smallint    NOT NULL,
    bimestre                smallint    NOT NULL,
    mes                     smallint    NOT NULL,
    nome_mes                text        NOT NULL,
    mes_ano                 text        NOT NULL,
    eh_fim_bimestre         smallint    NOT NULL CHECK (eh_fim_bimestre IN (0, 1)),
    eh_fim_quadrimestre     smallint    NOT NULL CHECK (eh_fim_quadrimestre IN (0, 1)),
    eh_fim_semestre         smallint    NOT NULL CHECK (eh_fim_semestre IN (0, 1)),
    eh_fim_exercicio        smallint    NOT NULL CHECK (eh_fim_exercicio IN (0, 1)),
    label_periodo_rreo      text        NOT NULL,
    label_periodo_rgf       text        NOT NULL
);

CREATE TABLE IF NOT EXISTS gold.d_ente (
    sk_ente             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ente             integer     NOT NULL UNIQUE,
    nome_ente           text        NOT NULL,
    uf                  char(2)     NOT NULL,
    regiao              char(2),
    esfera              text        NOT NULL,
    capital             smallint    CHECK (capital IN (0, 1)),
    co_cnpj             text,
    populacao_ref       integer,
    ano_ref_populacao   smallint,
    eh_ente_principal   smallint    NOT NULL DEFAULT 0 CHECK (eh_ente_principal IN (0, 1))
);

CREATE TABLE IF NOT EXISTS gold.d_poder (
    sk_poder            integer     PRIMARY KEY,
    co_poder            text        NOT NULL UNIQUE,
    nome_poder          text        NOT NULL
);

INSERT INTO gold.d_poder (sk_poder, co_poder, nome_poder) VALUES
    (1, 'E', 'Poder Executivo'),
    (2, 'L', 'Poder Legislativo'),
    (3, 'CONSOLIDADO', 'Ente Consolidado')
ON CONFLICT (sk_poder) DO UPDATE
    SET co_poder = EXCLUDED.co_poder,
        nome_poder = EXCLUDED.nome_poder;

CREATE TABLE IF NOT EXISTS gold.d_coluna (
    sk_coluna               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coluna_padrao           text        NOT NULL UNIQUE,
    coluna_origem_exemplo   text,
    tipo_medida             text        NOT NULL CHECK (tipo_medida IN (
                                'FLUXO_PERIODO', 'FLUXO_ACUMULADO', 'PREVISAO',
                                'ESTOQUE', 'PERCENTUAL', 'SALDO'
                            )),
    aditividade             text        NOT NULL CHECK (aditividade IN (
                                'ADITIVA', 'SEMIADITIVA', 'NAO_ADITIVA'
                            )),
    ordem_exibicao          integer
);

CREATE TABLE IF NOT EXISTS gold.d_secao (
    sk_secao        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte           text        NOT NULL CHECK (fonte IN ('DCA', 'RREO', 'RGF')),
    anexo_codigo    text        NOT NULL,
    secao_codigo    text        NOT NULL,
    secao_nome      text        NOT NULL,
    ordem_exibicao  integer,
    UNIQUE (fonte, anexo_codigo, secao_codigo)
);

CREATE TABLE IF NOT EXISTS gold.d_conta (
    sk_conta            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fonte               text        NOT NULL CHECK (fonte IN ('DCA', 'RREO', 'RGF')),
    anexo_codigo        text        NOT NULL,
    cod_conta           text        NOT NULL,
    cod_conta_padrao    text        NOT NULL,
    descricao           text,
    cod_conta_pai       text,
    nivel               smallint,
    caminho             text,
    eh_folha            smallint    NOT NULL DEFAULT 0 CHECK (eh_folha IN (0, 1)),
    eh_total            smallint    NOT NULL DEFAULT 0 CHECK (eh_total IN (0, 1)),
    grupo_analitico     text,
    sinal_semantico     smallint    NOT NULL DEFAULT 1 CHECK (sinal_semantico IN (-1, 1)),
    vigencia_ini        date        NOT NULL DEFAULT DATE '1900-01-01',
    vigencia_fim        date,
    CONSTRAINT ck_d_conta_folha_total CHECK (NOT (eh_folha = 1 AND eh_total = 1)),
    UNIQUE (fonte, anexo_codigo, cod_conta, vigencia_ini)
);

CREATE TABLE IF NOT EXISTS gold.d_funcao (
    sk_funcao       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_funcao      text        NOT NULL,
    nome_funcao     text        NOT NULL,
    cod_subfuncao   text        NOT NULL DEFAULT '',
    nome_subfuncao  text,
    nivel           text        NOT NULL CHECK (nivel IN ('NAO_APLICA', 'FUNCAO', 'SUBFUNCAO')),
    UNIQUE (cod_funcao, cod_subfuncao)
);

INSERT INTO gold.d_funcao (sk_funcao, cod_funcao, nome_funcao, cod_subfuncao, nome_subfuncao, nivel)
VALUES (0, '00', 'Não se aplica', '', 'Não se aplica', 'NAO_APLICA')
ON CONFLICT (sk_funcao) DO NOTHING;

CREATE TABLE IF NOT EXISTS gold.d_natureza_despesa (
    sk_natureza         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_natureza        text        NOT NULL UNIQUE,
    nome_natureza       text        NOT NULL,
    categoria_economica text        CHECK (categoria_economica IN ('NAO_APLICA', 'CORRENTE', 'CAPITAL', 'INTRA')),
    grupo_despesa       text
);

INSERT INTO gold.d_natureza_despesa (sk_natureza, cod_natureza, nome_natureza, categoria_economica, grupo_despesa)
VALUES (0, '0', 'Não se aplica', 'NAO_APLICA', 'Não se aplica')
ON CONFLICT (sk_natureza) DO NOTHING;

CREATE TABLE IF NOT EXISTS gold.d_fonte_recurso (
    sk_fonte_recurso    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_fonte           text        NOT NULL UNIQUE,
    cod_fonte_padrao    text        NOT NULL,
    nome_fonte          text        NOT NULL,
    grupo               text        CHECK (grupo IS NULL OR grupo IN (
                            'LIVRE', 'SAUDE', 'EDUCACAO', 'PREVIDENCIA', 'OUTRAS_VINCULADAS'
                        )),
    vinculada           smallint    NOT NULL CHECK (vinculada IN (0, 1))
);

INSERT INTO gold.d_fonte_recurso (sk_fonte_recurso, cod_fonte, cod_fonte_padrao, nome_fonte, grupo, vinculada)
VALUES (0, '0', '0', 'Não se aplica', NULL, 0)
ON CONFLICT (sk_fonte_recurso) DO NOTHING;

CREATE TABLE IF NOT EXISTS gold.d_limite_lrf (
    sk_limite           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_limite       text            NOT NULL,
    descricao           text            NOT NULL,
    percentual_limite   numeric(12,6)   NOT NULL,
    pct_alerta          numeric(12,6),
    pct_prudencial      numeric(12,6),
    tipo_limite         text            NOT NULL CHECK (tipo_limite IN ('MAXIMO', 'MINIMO')),
    base_calculo        text            NOT NULL,
    vigencia_ini        date            NOT NULL,
    vigencia_fim        date,
    base_legal          text,
    UNIQUE (codigo_limite, vigencia_ini)
);

CREATE TABLE IF NOT EXISTS gold.d_indicador (
    sk_indicador        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_indicador    text            NOT NULL UNIQUE,
    nome                text            NOT NULL,
    descricao           text,
    formula_texto       text            NOT NULL,
    unidade             text            NOT NULL CHECK (unidade IN (
                            'PERCENTUAL', 'RAZAO', 'REAIS', 'REAIS_PER_CAPITA'
                        )),
    sentido_bom         text            NOT NULL CHECK (sentido_bom IN (
                            'MAIOR_MELHOR', 'MENOR_MELHOR', 'FAIXA'
                        )),
    valor_referencia    numeric(12,6),
    fonte_primaria      text            NOT NULL,
    grupo               text            NOT NULL,
    camada_calculo      text            NOT NULL CHECK (camada_calculo IN ('GOLD_MATERIALIZADO', 'DAX')),
    ordem_exibicao      integer
);
